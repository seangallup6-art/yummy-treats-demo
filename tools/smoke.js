const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await ctx.newPage();
  const errs = [];
  page.on('pageerror', e => errs.push(e.message));
  const base = 'http://127.0.0.1:9400';
  await page.goto(base + '/', { waitUntil: 'networkidle', timeout: 180000 });
  await page.goto(base + '/product/chicken-jerky-strips/', { waitUntil: 'networkidle', timeout: 180000 });
  await page.click('.yt-variations__btn[data-value="250-g"], .yt-variations__btn:nth-child(2)');
  await page.waitForTimeout(800);
  const price = await page.textContent('.woocommerce-variation-price').catch(() => 'n/a');
  const btnDisabled = await page.$eval('.single_add_to_cart_button', b => b.disabled || b.classList.contains('disabled'));
  console.log('variation price:', (price || '').trim().replace(/\s+/g, ' '), '| add-to-cart disabled:', btnDisabled);
  await page.click('.single_add_to_cart_button');
  await page.waitForTimeout(4000);
  const notice = await page.textContent('.woocommerce-message, .wc-block-components-notice-banner').catch(() => 'no notice');
  console.log('notice:', (notice || '').trim().replace(/\s+/g, ' ').slice(0, 120));
  await page.goto(base + '/cart/', { waitUntil: 'load', timeout: 180000 });
  await page.waitForSelector('.wc-block-cart-items__row', { timeout: 60000 }).catch(() => {});
  await page.waitForTimeout(2000);
  const items = await page.$$eval('.wc-block-cart-items__row', r => r.length);
  const freebar = await page.textContent('.yt-freebar__msg').catch(() => 'none');
  console.log('cart rows:', items, '| freebar:', freebar);
  await page.screenshot({ path: '/tmp/shots/cart.png', fullPage: true });
  await page.goto(base + '/checkout/', { waitUntil: 'load', timeout: 180000 });
  await page.waitForSelector('.wc-block-components-checkout-step', { timeout: 60000 }).catch(() => {});
  await page.waitForTimeout(3000);
  const methods = await page.$$eval('.wc-block-components-radio-control__label, .wc-block-components-radio-control-accordion-option__label, .wc-block-components-payment-method-label', els => els.map(e => e.textContent.trim()));
  console.log('payment/shipping labels:', methods.join(' | '));
  const fields = await page.$$eval('.wc-block-components-text-input label, .wc-block-components-checkbox label, .wc-block-components-combobox label', els => els.map(e => e.textContent.trim()));
  console.log('fields:', fields.join(' | '));
  await page.screenshot({ path: '/tmp/shots/checkout.png', fullPage: true });
  console.log('page errors:', errs.length ? errs.join('\n') : 'none');
  await browser.close();
})();
